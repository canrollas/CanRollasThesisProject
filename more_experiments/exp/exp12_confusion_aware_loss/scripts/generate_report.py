#!/usr/bin/env python3
"""Assembles results/results.csv (final per-variant, per-fold metrics) and
results/reports/{config_id}/report.json (evaluate.py's per-variant
confusion/stage-pair/paired-comparison breakdown) into one Markdown report,
results/report.md -- the brief's Section 7 "Short Markdown research report
summarizing the findings" deliverable.

Only writes FACTUAL tables pulled directly from the CSV/JSON files already
on disk -- no interpretation, no claims about which variant "wins", since
that judgment belongs in the thesis text once real (non-smoke) numbers
exist, not hardcoded into this script. Run after evaluate.py has been run
for every config_id you want included.

Usage:
  python generate_report.py --config-ids mit_b1__corn__exp12_baseline \
      mit_b1__corn__exp12A_lam0.1 mit_b1__corn__exp12B_lam0.1_alpha1 \
      mit_b1__corn__exp12C_beta0.5
"""
import argparse
import csv
import json
from pathlib import Path

THIS_DIR = Path(__file__).resolve().parent
EXP_DIR = THIS_DIR.parent


def load_results_rows(config_ids):
    path = EXP_DIR / "results" / "results.csv"
    if not path.is_file():
        return []
    with open(path, newline="") as f:
        rows = list(csv.DictReader(f))
    return [r for r in rows if r["config_id"] in config_ids]


def mean_std(values):
    n = len(values)
    if n == 0:
        return float("nan"), float("nan")
    mean = sum(values) / n
    var = sum((v - mean) ** 2 for v in values) / n
    return mean, var ** 0.5


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--config-ids", nargs="+", required=True)
    args = p.parse_args()

    rows = load_results_rows(args.config_ids)
    lines = ["# Exp-12 -- Confusion-Aware CORN Loss: Results\n"]

    lines.append("## Pooled per-fold test metrics (mean +/- std over available folds)\n")
    lines.append("| config_id | n_folds | accuracy | macro_f1 | mae | qwk |")
    lines.append("|---|---|---|---|---|---|")
    for cid in args.config_ids:
        cid_rows = [r for r in rows if r["config_id"] == cid]
        if not cid_rows:
            lines.append(f"| {cid} | 0 | -- | -- | -- | -- |")
            continue
        acc_m, acc_s = mean_std([float(r["accuracy"]) for r in cid_rows])
        f1_m, f1_s = mean_std([float(r["macro_f1"]) for r in cid_rows])
        mae_m, mae_s = mean_std([float(r["mae"]) for r in cid_rows])
        qwk_m, qwk_s = mean_std([float(r["qwk"]) for r in cid_rows])
        lines.append(
            f"| {cid} | {len(cid_rows)} | {acc_m:.4f}±{acc_s:.4f} | {f1_m:.4f}±{f1_s:.4f} | "
            f"{mae_m:.4f}±{mae_s:.4f} | {qwk_m:.4f}±{qwk_s:.4f} |"
        )

    lines.append("\n## Stage-pair error breakdown (pooled, from evaluate.py reports)\n")
    lines.append("| config_id | total_errors | adjacent | non_adjacent | stage3->4 | stage4->3 |")
    lines.append("|---|---|---|---|---|---|")
    for cid in args.config_ids:
        report_path = EXP_DIR / "results" / "reports" / cid / "report.json"
        if not report_path.is_file():
            lines.append(f"| {cid} | -- | -- | -- | -- | -- |")
            continue
        report = json.load(open(report_path))
        sp = report["pooled"]["stage_pairs"]
        lines.append(
            f"| {cid} | {sp['total_errors']} | {sp['adjacent_errors']} | {sp['non_adjacent_errors']} | "
            f"{sp['stage3_to_stage4']} | {sp['stage4_to_stage3']} |"
        )

    lines.append("\n## Paired comparison vs. baseline (matched by image path)\n")
    lines.append("| config_id | fixed | regressed | net_change | both_correct | both_wrong |")
    lines.append("|---|---|---|---|---|---|")
    for cid in args.config_ids:
        report_path = EXP_DIR / "results" / "reports" / cid / "report.json"
        if not report_path.is_file():
            continue
        report = json.load(open(report_path))
        pc = report.get("paired_vs_baseline")
        if pc is None:
            continue
        lines.append(
            f"| {cid} | {pc['fixed']} | {pc['regressed']} | {pc['net_change']:+d} | "
            f"{pc['both_correct']} | {pc['both_wrong']} |"
        )

    lines.append("\n## Per-stage precision/recall/F1 (pooled)\n")
    for cid in args.config_ids:
        report_path = EXP_DIR / "results" / "reports" / cid / "report.json"
        if not report_path.is_file():
            continue
        report = json.load(open(report_path))
        lines.append(f"\n### {cid}\n")
        lines.append("| stage | precision | recall | f1 | support |")
        lines.append("|---|---|---|---|---|")
        for stage, m in report["pooled"]["per_stage"].items():
            lines.append(f"| {stage} | {m['precision']:.4f} | {m['recall']:.4f} | {m['f1']:.4f} | {m['support']} |")

    lines.append(
        "\n---\n*Generated by scripts/generate_report.py directly from results/results.csv and "
        "results/reports/*/report.json -- no number in this file is estimated or hand-written.*"
    )

    out_path = EXP_DIR / "results" / "report.md"
    out_path.write_text("\n".join(lines))
    print(f"wrote {out_path}")


if __name__ == "__main__":
    main()
