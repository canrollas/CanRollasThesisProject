#!/usr/bin/env python3
"""Refresh the portable notebook's embedded, deterministic source ZIP.

Run after changing the experiment or its shared dependencies. No data,
checkpoints, notebook outputs or clinical images are embedded.
"""
import base64
import hashlib
import io
import json
import re
import zipfile
from pathlib import Path

EXP_DIR = Path(__file__).resolve().parents[1]
REPO_ROOT = EXP_DIR.parents[2]


def main():
    paths = [EXP_DIR / "README.md", *sorted((EXP_DIR / "configs").glob("*.yaml"))]
    paths += sorted((EXP_DIR / "scripts").glob("*.py"))
    paths += sorted((EXP_DIR / "tests").glob("*.py"))
    paths += sorted((REPO_ROOT / "task_3" / "src").glob("*.py"))
    paths += [
        REPO_ROOT / "task_3" / "requirements.txt",
        REPO_ROOT / "task_3" / "configs" / "mit_b1_corn_baseline_protocol.json",
        REPO_ROOT / "more_experiments" / "exp" / "exp4_late_fusion" / "scripts" / "model.py",
    ]
    stream = io.BytesIO()
    with zipfile.ZipFile(stream, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for path in sorted(set(paths)):
            info = zipfile.ZipInfo(str(path.relative_to(REPO_ROOT)), date_time=(2026, 11, 3, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(info, path.read_bytes())
    payload = stream.getvalue()
    encoded = base64.b64encode(payload).decode("ascii")
    notebook_path = EXP_DIR / "colab_train.ipynb"
    notebook = json.loads(notebook_path.read_text())
    matches = 0
    for cell in notebook["cells"]:
        if cell["cell_type"] != "code":
            continue
        source = "".join(cell["source"])
        if "BUNDLED_SOURCE_ZIP_BASE64 = " in source:
            source, count = re.subn(
                r'^BUNDLED_SOURCE_ZIP_BASE64 = .*$',
                'BUNDLED_SOURCE_ZIP_BASE64 = "' + encoded + '"  # Generated by scripts/bundle_notebook.py',
                source, flags=re.MULTILINE,
            )
            matches += count
            cell["source"] = source.splitlines(keepends=True)
    if matches != 1:
        raise ValueError(f"Expected exactly one embedded-source marker, found {matches}")
    notebook_path.write_text(json.dumps(notebook, ensure_ascii=False, indent=1) + "\n")
    print(f"Bundled {len(set(paths))} source files ({len(payload):,} bytes); SHA256={hashlib.sha256(payload).hexdigest()}")


if __name__ == "__main__":
    main()
